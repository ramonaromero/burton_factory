        <strong>¿Qué es una cookie?</strong>
<p>Este sitio web utiliza cookies y/o tecnologías similares que almacenan y recuperan información cuando navegas. En general, estas tecnologías pueden servir para finalidades muy 
diversas, como, por ejemplo, reconocerte como usuario, obtener información sobre tus hábitos de navegación, o personalizar la forma en que se muestra el contenido. Los usos 
concretos que hacemos de estas tecnologías se describen a continuación.</p>
<strong>¿Qué tipos de cookies existen?</strong>
<p>Según quien realice la gestión hay:</p>
<ul>
<li>Cookies propias: Son aquellas que se envían al equipo terminal del usuario desde un equipo o dominio gestionado por el propio editor y desde el que se presta el servicio 
solicitado por el usuario.</li>
<li>Cookies de terceros: Son aquellas que se envían al equipo terminal del usuario desde un equipo o dominio que no es gestionado por el editor, sino por otra entidad que 
trata los datos obtenidos través de las cookies.</li>
</ul>
<p>Según el tipo de finalidad hay:</p>
<ul>
<li>Cookies técnicas: Son aquellas que permiten al usuario la navegación a través de una página web, plataforma o aplicación y la utilización de las diferentes opciones/servicios 
que existen en ella (por ejemplo: identificar una sesión, acceder a lugares de acceso restringido, recordar elementos que integran una compra, realizar el proceso de compra de 
un pedido, almacenar contenidos para la difusión de videos o sonido o compartir contenidos a través de redes sociales, etc.).</li>
<li>Analíticas: Son aquellas que, tratadas por nosotros o por terceros, nos permiten cuantificar el número de usuarios y así realizar la medición y análisis estadístico de la 
utilización que hacen los usuarios del servicio ofertado. Para ello se analiza su navegación en nuestra página web con el fin de mejorar la oferta de productos o servicios que 
le ofrecemos.</li>
<li>Cookies de preferencias o personalización: Las cookies de personalización son las que permiten recordar las preferencias de los usuarios cuando navegan en una web que ya han 
visitado. Por ejemplo permiten recordar el idioma preferido de uso de la web, la región en la cual se encuentra el usuario para proponerle contenido adecuado, o también el tipo de
navegador a través del cual acceder a un servicio concreto etc. Las cookies de preferencias son también las que permiten cambiar el tamaño del texto, la fuente o las otras partes 
de las páginas web que se pueden personalizar. El objetivo de las cookies de personalización es ofrecer a los usuarios una navegación más fácil, fluida y personalizada.</li>
<li>Cookies de redes sociales y otros plugins: Estas cookies permiten a los usuarios interactuar con el contenido de un sitio web en las redes sociales como Facebook, X, 
YouTube etc. Un ejemplo del uso de esta cookie seria compartir un sitio en Facebook o hacer clic en “Me gusta”. Las condiciones de uso y la información recopilada de estas cookies 
están reguladas por las propias plataformas sociales.</li>
<li>Cookies publicitarias: Son aquellas que permiten la gestión, de la forma más eficaz posible, de los espacios publicitarios que, en su caso, el editor haya incluido en una página 
web, aplicación o plataforma desde la que presta el servicio solicitado en base a criterios como el contenido editado o la frecuencia en la que se muestran los anuncios.</li>
<li>Publicitarias comportamentales: Son aquellas que, tratadas por nosotros o por terceros, nos permiten analizar sus hábitos de navegación en Internet para que podamos mostrarle 
publicidad relacionada con su perfil de navegación.</li>
</ul>
<strong>Según el plazo de tiempo que permanecen activas</strong>
<ul>
<li>Cookies de sesión: Son aquellas diseñadas para recabar y almacenar datos mientras el usuario accede a una página web. Se suelen emplear para almacenar información que solo 
interesa conservar para la prestación del servicio solicitado por el usuario en una sola ocasión (por ejemplo, una lista de productos adquiridos) y desaparecen al terminar la sesión.</li>
<li>Cookies persistentes: Son aquellas en las que los datos siguen almacenados en el terminal y pueden ser accedidos y tratados durante un periodo definido por el responsable de la 
cookie, y que puede ir de unos minutos a varios años.</li>
</ul>
<strong>Niveles de intromisión asociados a las cookies que usamos:</strong>
<p>Las cookies incorporan un criterio de "nivel de intrusión" apoyado en una escala del 1 al 3, en la que:</p>
<ul>
<li>Nivel 1: Se corresponde con cookies de uso interno imprescindibles para la prestación del propio servicio solicitado por el usuario.</li>
<li>Nivel 2: Se corresponde con cookies anónimas de uso interno necesarias para el mantenimiento de contenidos y navegación, así como a cookies gestionadas por terceros en el marco 
de servicios solicitados expresamente por el usuario en las webs de aquellos (ej.: Complementos Sociales de Facebook, X o Linkedin, vídeos incrustados, mapas).</li>
<li>Nivel 3: Se corresponde con cookies gestionadas por terceros en el marco de servicios no solicitados expresamente por el usuario, permitiendo su seguimiento a través de webs 
de las que nuestra web no es titular (ej.: plataformas de gestión de publicidad gráfica). La especificación de este nivel viene acompañada de su titular. El uso de cookies de nivel 
3 está sujeto al permiso previo del usuario mediante confirmación expresa de su aceptación.</li>
</ul>
